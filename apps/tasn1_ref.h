/*
 * apps/tasn1_ref.h — DER this system did not produce.
 *
 * Generated on the build machine by OpenSSL 3.6.3, with these commands,
 * and then written out as bytes:
 *
 *     openssl ecparam -name prime256v1 -genkey -noout -out ec.pem
 *     openssl pkey  -in ec.pem -pubout -outform DER -out ec_spki.der
 *     openssl pkcs8 -topk8 -nocrypt -in ec.pem -outform DER -out ec_p8.der
 *     openssl genrsa -out rsa.pem 1024
 *     openssl rsa -in rsa.pem -RSAPublicKey_out -outform DER \
 *                 -out rsa_pub.der
 *
 * The reason it comes from somewhere else is the same reason
 * apps/jpeg_ref.h holds a bitstream macOS encoded: libtasn1 is both the
 * encoder and the decoder here, so a structure written with
 * asn1_der_coding and read back with asn1_der_decoding2 would agree with
 * itself even if both halves shared a wrong idea of how an OBJECT
 * IDENTIFIER or a BIT STRING is laid out. These bytes were produced by
 * an implementation that has never seen this one, and every check in
 * apps/tasn1test.c is ultimately against them.
 *
 * The keys are real but throwaway — generated for this file, used
 * nowhere, and public-key material in three of the four cases. The
 * PKCS#8 blob does carry a private scalar; it protects nothing and never
 * did.
 *
 * ---- the four blobs ----
 *
 *   ec_spki      SubjectPublicKeyInfo for a P-256 key. 91 bytes:
 *                SEQUENCE { AlgorithmIdentifier { id-ecPublicKey,
 *                prime256v1 }, BIT STRING (520 bits) }. The bit string
 *                is the uncompressed point, 0x04 || X || Y.
 *
 *   ec_spki_ber  the same 89 content bytes with the outer SEQUENCE
 *                re-headed `30 80 ... 00 00` — indefinite length, which
 *                is legal BER and illegal DER. It is here to give
 *                ASN1_DECODE_FLAG_STRICT_DER something to reject:
 *                a flag that is passed and never changes an answer is
 *                not a tested flag. libtasn1 accepts these bytes
 *                without it and refuses them with it, and the test
 *                asserts both directions.
 *
 *   ec_pkcs8     PrivateKeyInfo for the same key. version 0, the same
 *                AlgorithmIdentifier, and an OCTET STRING holding a
 *                complete ECPrivateKey — a nested structure, which is
 *                what makes it worth decoding: the outer parse must
 *                hand back the inner bytes intact.
 *
 *   rsa_pub      a PKCS#1 RSAPublicKey, 1024-bit. Two INTEGERs. The
 *                modulus is 129 bytes because DER's INTEGER is signed
 *                and the leading 0x00 is what keeps it positive —
 *                the single most common thing for a hand-rolled
 *                encoder to get wrong, and therefore worth asserting
 *                by exact length.
 */

